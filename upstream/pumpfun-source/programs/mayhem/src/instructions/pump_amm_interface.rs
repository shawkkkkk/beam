




















































































































































































































































































































































































#[inline(never)]
pub fn buy_cpi_failed(_error:anchor_lang::error::Error)->anchor_lang::error::Error {
    anchor_lang::error!(super::pump_swap_types::PumpSwapError::PumpSwapCpiFailed)
}





















#[inline(always)]
pub fn bought_amounts(before_quote:u64,after_quote:u64,before_tokens:u64,after_tokens:u64)->(u64,u64) {


    let quote_spent = before_quote-after_quote;
     let tokens_bought = after_tokens-before_tokens;
    (quote_spent,tokens_bought)
}































































































































































#[inline(never)]
pub fn sell_cpi_failed(_error:anchor_lang::error::Error)->anchor_lang::error::Error {
    anchor_lang::error!(super::pump_swap_types::PumpSwapError::PumpSwapCpiFailed)
}























#[inline(always)]
pub fn sold_amounts(before_quote:u64,after_quote:u64,before_tokens:u64,after_tokens:u64)->(u64,u64) {
   let quote_gained = after_quote-before_quote;
    let tokens_removed = before_tokens-after_tokens;
    (quote_gained,tokens_removed)
}
