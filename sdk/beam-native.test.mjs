import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import {
  PROGRAM_ID, decodeBase58Pubkey, encodeBase58Pubkey,
  encodeCreate, encodeBuy, encodeSell, buildCreate, buildBuy, buildSell,
  decodeCompleteEvent, decodeCurrentBondingCurve,
} from './beam-native.mjs';

const fixture = JSON.parse(readFileSync(new URL('./fixtures/native-sol.json', import.meta.url)));
const hex = (bytes) => Buffer.from(bytes).toString('hex');
const asStrings = (value) => Object.fromEntries(Object.entries(value).map(([key, v]) => [key, typeof v === 'bigint' ? v.toString() : v]));

test('golden legacy instruction bytes and account metas match Anchor output', () => {
  assert.equal(PROGRAM_ID, fixture.programId);
  for (const [kind, encode, build] of [
    ['create', encodeCreate, buildCreate],
    ['buy', encodeBuy, buildBuy],
    ['sell', encodeSell, buildSell],
  ]) {
    const expected = fixture[kind];
    assert.equal(hex(encode(expected.args)), expected.dataHex, `${kind} data`);
    const instruction = build(expected.accounts, expected.args);
    assert.equal(instruction.programId, PROGRAM_ID);
    assert.equal(hex(instruction.data), expected.dataHex);
    assert.deepEqual(instruction.keys, expected.metas, `${kind} metas`);
  }
  assert.equal(fixture.create.metas.length, 14);
  assert.equal(fixture.buy.metas.length, 16);
  assert.equal(fixture.sell.metas.length, 14);
});

test('base58 pubkeys roundtrip and malformed keys fail', () => {
  const zero = '11111111111111111111111111111111';
  assert.equal(encodeBase58Pubkey(decodeBase58Pubkey(zero)), zero);
  assert.equal(encodeBase58Pubkey(decodeBase58Pubkey(fixture.create.args.creator)), fixture.create.args.creator);
  assert.throws(() => decodeBase58Pubkey('0'), /invalid base58/);
  assert.throws(() => decodeBase58Pubkey('2'), /32 bytes/);
  assert.throws(() => decodeBase58Pubkey('1'.repeat(45)), /too long/);
  assert.throws(() => decodeBase58Pubkey('z'.repeat(100_000)), /too long/);
  assert.throws(() => encodeBase58Pubkey(new Uint8Array(31)), /32 bytes/);
});

test('u64 encoding accepts exact bigint and rejects unsafe or malformed amounts', () => {
  const base = { ...fixture.sell.args, amount: (1n << 64n) - 1n };
  assert.equal(hex(encodeSell(base)).slice(16, 32), 'ffffffffffffffff');
  assert.throws(() => encodeSell({ ...base, amount: 1n << 64n }), /fit u64/);
  assert.throws(() => encodeSell({ ...base, amount: -1n }), /fit u64/);
  assert.throws(() => encodeSell({ ...base, amount: Number.MAX_SAFE_INTEGER + 1 }), /safe integer/);
  assert.throws(() => encodeSell({ ...base, amount: '01' }), /canonical decimal/);
  assert.throws(() => encodeSell({ ...base, amount: '9'.repeat(100_000) }), /fit u64/);
  assert.throws(() => encodeBuy({ ...fixture.buy.args, partialFill: 1 }), /boolean/);
  const unicode = encodeCreate({ ...fixture.create.args, name: '⚡' });
  assert.equal(new DataView(unicode.buffer, unicode.byteOffset, unicode.byteLength).getUint32(8, true), 3);
});

test('builders reject missing accounts and a substituted self-CPI program', () => {
  const missing = { ...fixture.create.accounts };
  delete missing.metadata;
  assert.throws(() => buildCreate(missing, fixture.create.args), /pubkey/);
  assert.throws(() => buildCreate({ ...fixture.create.accounts, program: fixture.create.accounts.mint }, fixture.create.args), /self-CPI/);
});

test('current curve and completion event decode against Rust-generated bytes', () => {
  const complete = decodeCompleteEvent(Buffer.from(fixture.completeEvent.dataHex, 'hex'));
  assert.deepEqual(asStrings(complete), fixture.completeEvent.expected);
  const curve = decodeCurrentBondingCurve(Buffer.from(fixture.currentBondingCurve.dataHex, 'hex'));
  assert.deepEqual(asStrings(curve), fixture.currentBondingCurve.expected);
  const padded = new Uint8Array(168);
  padded.set(Buffer.from(fixture.currentBondingCurve.dataHex, 'hex'), 1);
  assert.deepEqual(asStrings(decodeCurrentBondingCurve(padded.subarray(1, 167))), fixture.currentBondingCurve.expected);
  const short = Buffer.from(fixture.currentBondingCurve.dataHex, 'hex').subarray(0, 165);
  assert.throws(() => decodeCurrentBondingCurve(short), /166-byte/);
  const badFlag = Buffer.from(fixture.currentBondingCurve.dataHex, 'hex');
  badFlag[48] = 2;
  assert.throws(() => decodeCurrentBondingCurve(badFlag), /boolean/);
  const badEvent = Buffer.from(fixture.completeEvent.dataHex, 'hex');
  badEvent[0] ^= 1;
  assert.throws(() => decodeCompleteEvent(badEvent), /CompleteEvent/);
});
